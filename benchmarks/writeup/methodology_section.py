from __future__ import annotations

METHODOLOGY = (
    "One Node load generator drives both databases, with a thin per-database adapter for each. Sirannon runs "
    "over its SDK's default WebSocket transport, which multiplexes every concurrent request over one persistent "
    "socket; PostgreSQL runs over node-postgres on its binary socket protocol. Both engines answer on the same "
    "host over loopback. Sirannon's WebSocket path carries JSON framing on every call, heavier than PostgreSQL's "
    "binary protocol, and the numbers include that cost because it is Sirannon's client path. Before each sweep "
    "the generator measures each client's own throughput ceiling against the live engine and records it with the "
    "results, so a rate that falls short reflects the database's limit.\n\n"
    "Both engines run as native processes under Linux cgroup v2 control. The engine under test is pinned to its "
    "own CPU cores with a hard memory ceiling, sized so the dataset cannot be served from RAM alone, and the "
    "load generator runs on disjoint cores with no memory cap. Each engine writes to a data directory the "
    "harness first proves, at device level, to be on the machine's local NVMe. The engines run one after the "
    "other, each engine process starts fresh for its pass and is stopped after it, so neither engine carries a "
    "warm buffer pool between passes, and Sirannon's data directory is removed after each of its passes. "
    "Between passes the harness applies a disclosed cooldown: it syncs and waits for dirty pages to drain, "
    "trims the data filesystem, and pauses for a fixed interval. The operating system page cache is dropped "
    "before each measured series, so neither engine starts warm from the other's run.\n\n"
    "The harness matches durability at two levels. Full durability sets PostgreSQL `synchronous_commit=on` "
    "against Sirannon `synchronous=full`, so both fsync every commit. Matched-relaxed sets `synchronous_commit=off` "
    "against Sirannon `synchronous=normal` in WAL mode, so both defer the fsync and both can lose only the most "
    "recent commits on power loss without corrupting.\n\n"
    "The load is open-loop. Requests arrive at a fixed target rate whether or not earlier requests have "
    "returned, and each request's latency counts from the time it was meant to be sent, which corrects for "
    "coordinated omission. The report uses tail-latency percentiles, and the operating point is the highest "
    "offered rate the engine sustained while holding p99 under the recorded target.\n\n"
    "The sweep's measured windows are short, so on selected workloads the harness then holds each engine at "
    "its operating point for one long continuous window that crosses both engines' checkpoint cycles, and "
    "reports the pace and tail latency of every 30-second slice of it. This shows whether the operating "
    "point survives the periodic housekeeping both engines defer, which a short window cannot contain."
)
