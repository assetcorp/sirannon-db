import type { OperationManifest, OperationShape } from './manifest.js'
import {
  distinct,
  GeneratedNames,
  type NameClaimant,
  type OperationGroup,
  operationClaimant,
  operationGroups,
  pascalCase,
} from './names.js'

const PYTHON_KEYWORDS = new Set([
  'False',
  'None',
  'True',
  'and',
  'as',
  'assert',
  'async',
  'await',
  'break',
  'class',
  'continue',
  'def',
  'del',
  'elif',
  'else',
  'except',
  'finally',
  'for',
  'from',
  'global',
  'if',
  'import',
  'in',
  'is',
  'lambda',
  'nonlocal',
  'not',
  'or',
  'pass',
  'raise',
  'return',
  'try',
  'while',
  'with',
  'yield',
])

const RESERVED_MODULE_NAMES = new Set(['Any', 'ReadRef', 'TypedDict', 'WriteRef', 'REGISTRY_DIGEST'])

const OPEN_ROW = 'dict[str, Any]'

const OUTSIDE_PRINTABLE_ASCII = /[^\x20-\x7e]/gu

/**
 * Returns Python source that declares a typed `ReadRef` or `WriteRef` for every operation in a manifest.
 *
 * Each database becomes a class whose `Reads` and `Writes` classes hold one reference per operation, and the
 * shared operations become the `SharedOperations` class. Every argument and every derived column becomes a key of
 * a `TypedDict`, so a type checker refuses an argument or a column that the server does not serve.
 *
 * @param manifest - The operations to render.
 * @returns The Python source to write.
 *
 * @public
 */
export function renderPythonOperations(manifest: OperationManifest): string {
  const names = new GeneratedNames()
  const declarations: string[] = []
  const namespaces: string[] = []

  for (const group of operationGroups(manifest)) {
    const className = names.claim(pythonClassName(`${group.stem}Operations`), group.claimant)
    const reads = renderKind(group, 'reads', names, declarations)
    const writes = renderKind(group, 'writes', names, declarations)
    const namespace = [
      `class ${className}:`,
      `    """${groupDescription(group)}"""`,
      '',
      '    class Reads:',
      ...(reads.length === 0 ? ['        pass'] : reads),
      '',
      '    class Writes:',
      ...(writes.length === 0 ? ['        pass'] : writes),
    ]
    namespaces.push(namespace.join('\n'))
  }

  const lines = [
    '"""Generated by sirannon-codegen from the operation registry. Do not edit."""',
    '',
    'from typing import Any, TypedDict',
    '',
    'from sirannon_client import ReadRef, WriteRef',
    '',
    `REGISTRY_DIGEST: str | None = ${manifest.digest === undefined ? 'None' : pythonText(manifest.digest)}`,
    ...[...declarations, ...namespaces].flatMap(block => ['', '', block]),
  ]
  return `${lines.join('\n')}\n`
}

function renderKind(
  group: OperationGroup,
  kind: 'reads' | 'writes',
  names: GeneratedNames,
  declarations: string[],
): string[] {
  const members: string[] = []
  const memberNames = new GeneratedNames()
  for (const [name, shape] of Object.entries(group.operations[kind])) {
    const claimant = operationClaimant(group, kind, name)
    const stem = `${group.stem}${pascalCase(name) || 'Operation'}`
    const args = names.claim(pythonClassName(`${stem}Args`), claimant)
    declarations.push(typedDict(args, shape.args))
    const attribute = memberNames.claim(pythonAttribute(name), claimant)
    if (kind === 'writes') {
      members.push(`        ${attribute}: WriteRef[${args}] = WriteRef(${pythonText(name)})`)
      continue
    }
    const row = rowType(stem, shape, claimant, names, declarations)
    members.push(`        ${attribute}: ReadRef[${args}, ${row}] = ReadRef(${pythonText(name)})`)
  }
  return members
}

function groupDescription(group: OperationGroup): string {
  if (group.shared) return 'The registered operations that every database serves.'
  return `The registered operations of the ${doubleQuotedAscii(group.claimant.label)} database.`
}

function rowType(
  stem: string,
  shape: OperationShape,
  claimant: NameClaimant,
  names: GeneratedNames,
  declarations: string[],
): string {
  if (shape.columns === null) return OPEN_ROW
  const row = names.claim(pythonClassName(`${stem}Row`), claimant)
  declarations.push(typedDict(row, shape.columns))
  return row
}

function typedDict(typeName: string, keys: readonly string[]): string {
  const listed = distinct(keys)
  if (listed.every(classBodyKey)) {
    const fields = listed.length === 0 ? ['    pass'] : listed.map(key => `    ${key}: Any`)
    return [`class ${typeName}(TypedDict):`, ...fields].join('\n')
  }
  const entries = listed.map(key => `${pythonText(key)}: Any`).join(', ')
  return `${typeName} = TypedDict(${pythonText(typeName)}, {${entries}})`
}

function classBodyKey(key: string): boolean {
  return (
    /^[A-Za-z_][A-Za-z0-9_]*$/.test(key) &&
    !key.startsWith('__') &&
    !PYTHON_KEYWORDS.has(key) &&
    !RESERVED_MODULE_NAMES.has(key)
  )
}

function doubleQuotedAscii(value: string): string {
  return JSON.stringify(value).replace(OUTSIDE_PRINTABLE_ASCII, character => {
    const code = character.codePointAt(0) ?? 0
    return code > 0xffff ? `\\U${code.toString(16).padStart(8, '0')}` : `\\u${code.toString(16).padStart(4, '0')}`
  })
}

function pythonText(value: string): string {
  const quoted = doubleQuotedAscii(value)
  if (!value.includes('"') || value.includes("'")) return quoted
  return `'${quoted.slice(1, -1).replaceAll('\\"', '"')}'`
}

function pythonAttribute(name: string): string {
  const cleaned = name.replace(/[^A-Za-z0-9_]/g, '_')
  if (cleaned === '' || /^[0-9]/.test(cleaned) || PYTHON_KEYWORDS.has(cleaned)) return `_${cleaned}`
  if (cleaned.startsWith('__')) return `op${cleaned}`
  return cleaned
}

function pythonClassName(name: string): string {
  return RESERVED_MODULE_NAMES.has(name) || /^[0-9]/.test(name) ? `_${name}` : name
}
